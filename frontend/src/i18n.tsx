function initialLocale(): Locale {
  let saved: string | null = null
  try {
    saved = localStorage.getItem('grab-locale')
  } catch {
    // Storage can be unavailable in hardened browser/WebView profiles.
  }
  if (LOCALES.some(({ value }) => value === saved)) return saved as Locale
  const language = navigator.language.toLowerCase()
  if (language.startsWith('zh-tw') || language.startsWith('zh-hk')) return 'zh-TW'
  if (language.startsWith('zh')) return 'zh-CN'
  if (language.startsWith('ja')) return 'ja'
  return 'en'
}

type Translate = (key: string, values?: Record<string, string | number>) => string
const interpolate: Translate = (key, values = {}) =>
  Object.entries(values).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
    key,
  )
const I18nContext = createContext<{ locale: Locale; setLocale: (locale: Locale) => void; t: Translate }>({
  locale: 'en',
  setLocale: () => undefined,
  t: (key, values) => interpolate(extraEnglish[key] ?? key, values),
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale)
  useEffect(() => {
    try {
      localStorage.setItem('grab-locale', locale)
    } catch {
      // The current selection still works for this session.
    }
    document.documentElement.lang = locale
  }, [locale])
  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (key: string, values: Record<string, string | number> = {}) =>
        Object.entries(values).reduce(
          (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
          messages[locale][key] ??
            (locale === 'en'
              ? (extraEnglish[key] ?? key)
              : extraMessages[key]?.[LOCALES.findIndex((item) => item.value === locale) - 1]) ??
            key,
        ),
    }),
    [locale],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
